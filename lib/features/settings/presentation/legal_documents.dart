/// Общий низкоуровневый показ юридического документа в виде выезжающей
/// снизу шторки. Вынесено в отдельный файл, чтобы Политика
/// конфиденциальности, Условия использования и Пользовательское
/// соглашение (оферта) были доступны из нескольких мест — "О программе"
/// и экран регистрации — без дублирования текста в трёх копиях.
void _showLegalSheet(BuildContext context, {required String title, required String body}) {
  final isDark = Theme.of(context).brightness == Brightness.dark;
  showModalBottomSheet(
    context: context,
    isScrollControlled: true,
    backgroundColor: Colors.transparent,
    builder: (_) => DraggableScrollableSheet(
      initialChildSize: 0.7,
      maxChildSize: 0.9,
      minChildSize: 0.4,
      builder: (_, scrollCtrl) => Container(
        decoration: BoxDecoration(
          color: isDark ? AppColors.darkCard : Colors.white,
          borderRadius: const BorderRadius.vertical(top: Radius.circular(24)),
        ),
        child: Column(
          children: [
            Container(
                margin: const EdgeInsets.only(top: 12),
                width: 40,
                height: 4,
                decoration: BoxDecoration(
                    color: AppColors.muted.withOpacity(0.3),
                    borderRadius: BorderRadius.circular(2))),
            Padding(
                padding: const EdgeInsets.all(20),
                child: Text(title,
                    style: TextStyle(
                        fontSize: 18,
                        fontWeight: FontWeight.w700,
                        color: isDark ? Colors.white : const Color(0xFF1A1A2E)))),
            Expanded(
              child: SingleChildScrollView(
                controller: scrollCtrl,
                padding: const EdgeInsets.fromLTRB(20, 0, 20, 30),
                child: Text(
                  body,
                  style: TextStyle(
                      fontSize: 14,
                      height: 1.6,
                      color: isDark
                          ? Colors.white.withOpacity(0.85)
                          : const Color(0xFF1A1A2E)),
                ),
              ),
            ),
          ],
        ),
      ),
    ),
  );
}

