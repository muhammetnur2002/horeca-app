import 'package:uuid/uuid.dart';

/// Генератор идентификаторов записей.
///
/// Идентификаторы создаёт устройство, а не база: это позволяет заводить
/// записи без сети и делает отправку на сервер идемпотентной — повторная
/// отправка той же строки гасится по первичному ключу.
///
/// Версия 7 упорядочена по времени, поэтому новые строки ложатся в конец
/// индекса и выборки «последние N» идут по порядку ключа.
class Ids {
  const Ids._();

  static const _uuid = Uuid();

  static String newId() => _uuid.v7();
}
